const WORD_MAP = new Map();
for (const p of PHRASES) {
  WORD_MAP.set(p.en.toLowerCase(), p);
  WORD_MAP.set(p.tulu, p);
  WORD_MAP.set(p.roman.toLowerCase(), p);
  WORD_MAP.set(p.kn, p);
  for (const token of [p.en, p.roman]) {
    for (const w of token.toLowerCase().replace(/[?.,!]/g, "").split(/\s+/)) {
      if (w.length > 2 && !WORD_MAP.has(w)) WORD_MAP.set(w, p);
    }
  }
}

const LETTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ".split("");

export function lookupPhrase(text) {
  const raw = (text || "").trim();
  if (!raw) return null;
  const lower = raw.toLowerCase().replace(/[?.,!]/g, "");
  const exact = PHRASES.find((p) =>
    [p.en, p.roman, p.tulu, p.kn].some((v) => v.toLowerCase().replace(/[?.,!]/g, "") === lower)
  );
  if (exact) return exact;
  return PHRASES.find((p) => lower.includes(p.en.toLowerCase().replace(/[?.,!]/g, ""))) || null;
}

export function translateText(text) {
  const raw = (text || "").trim();
  if (!raw) {
    return { en: "", tulu: "", roman: "", signs: [], note: "Type a phrase to translate." };
  }
  const phrase = lookupPhrase(raw);
  if (phrase) {
    return { ...phrase, signs: [...phrase.signs], note: "Matched SilentTalk Tulu lexicon." };
  }

  const words = raw.split(/\s+/);
  const signs = [];
  const tuluBits = [];
  const romanBits = [];
  const enBits = [];
  for (const word of words) {
    const clean = word.replace(/[?.,!]/g, "");
    const hit = WORD_MAP.get(clean.toLowerCase()) || WORD_MAP.get(clean);
    if (hit) {
      tuluBits.push(hit.tulu);
      romanBits.push(hit.roman);
      enBits.push(hit.en);
      signs.push(...hit.signs);
    } else {
      enBits.push(clean);
      tuluBits.push(clean);
      romanBits.push(clean);
      for (const ch of clean.toUpperCase()) {
        if (LETTERS.includes(ch)) signs.push(ch);
      }
    }
  }
  return {
    en: enBits.join(" "),
    tulu: tuluBits.join(" "),
    roman: romanBits.join(" "),
    kn: "",
    signs,
    note: "Partial lexicon match. Unknown words are fingerspelled in ISL letters."
  };
}

